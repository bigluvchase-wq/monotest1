for (const [phrase, expected] of cases) {
  test('голос: ' + phrase, () => {
    const got = V.parse(phrase, ctx);
    if (expected === null) { assert.equal(got, null); return; }
    assert.ok(got, 'команда не распознана');
    for (const [key, value] of Object.entries(expected)) assert.deepEqual(got[key], value, key);
  });
}

test('вклад из примера: 100 тыс. под 6% на год', () => {
  const got = V.parse('сделай мне вклад новый на 100 тыс рублей под 6 процентов на 1 год', ctx);
  assert.deepEqual([got.kind, got.principal, got.rate, got.months], ['deposit', 100000, 6, 12]);
});

test('напоминание из примера: скинуть 500 рублей другу сегодня в 18:00', () => {
  const got = V.parse('напомни мне скинуть 500 рублей сегодня в 6 вечера другу', ctx);
  assert.deepEqual([got.kind, got.title, got.date, got.time], ['reminder', 'Скинуть 500 рублей другу', '2026-11-10', '18:00']);
});

test('время без «утра/вечера» выбирает ближайшее будущее', () => {
  assert.equal(V.parseWhen('в 6', new Date(2026, 10, 10, 14, 0)).time, '18:00');
  assert.equal(V.parseWhen('в 6', new Date(2026, 10, 10, 4, 0)).time, '06:00');
  assert.equal(V.parseWhen('сегодня в 3 часа', new Date(2026, 10, 10, 10, 0)).time, '15:00');
});
